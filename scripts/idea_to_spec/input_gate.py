"""Код-гейт входных данных: что отсекается до вызова модели.

Зачем. Кейс `NEG-01-empty-idea` проверяет, что на пустом входе оркестратор
просит одну строку и не начинает прогон. Проверять это моделью оказалось
дорого и ненадёжно: все семь измеренных моделей (3B–12B, разные семейства)
на пустом входе начинали прогон и писали артефакты. Провал оказался общим
для всех моделей — значит, это не задача модели, а входная ошибка, которую
должен отсечь код.

Правило: пустой вход не порождает спецификацию. Ответ на него
детерминирован и не требует модели.

Модуль используется трансформом промпта (`scripts/promptfoo_transform.py`):
при пустом входе модель не вызывается, а подставляется готовый ответ.
"""

from __future__ import annotations

import json
import re
from typing import Any

#: Ответ на пустую идею: просим одну строку и не начинаем прогон.
#: Формат — как у оркестратора (`prompts/orchestrator.md`).
EMPTY_IDEA_ANSWER = json.dumps(
    {
        "mode": "auto",
        "stage": "intake",
        "completeness": {"passed": False, "missing": ["идея"]},
        "gate": {
            "name": "",
            "status": "",
            "missing": [],
            "return_to": "",
        },
        "questions": [
            "Вопрос: Опишите идею одной строкой — что хотите сделать? "
            "Зачем я это спрашиваю: без описания идеи нечего анализировать, "
            "и прогон не начнётся. Термины: строка — одно предложение о "
            "проблеме или желаемом результате; прошу прислать строку с идеей."
        ],
        "artifacts": [],
        "assumptions": [],
        "next": "intake",
    },
    ensure_ascii=False,
)

#: Знаки препинания и служебные символы, из которых может состоять вход.
#: Точка и многоточие исключены: «...» — это тоже намёк на идею, а не пустота.
_NOISE_RE = re.compile(r"^[\s\.,;:!?\-\u2013\u2014_/\\()\[\]{}<>\u00ab\u00bb\"`'*#@~]+$")
_DOT_ONLY_RE = re.compile(r"^\.+")


def is_empty_idea(text: str) -> bool:
    """Проверить, что вход не содержит идеи.

    Пустой вход — это пробелы, переводы строк или одни знаки препинания.
    Всё, что содержит хотя бы одну букву или цифру, идеей считается.

    Args:
        text: Вход пользователя.

    Returns:
        True, если идеи нет.
    """
    if not text or not text.strip():
        return True
    stripped = text.strip()
    if _DOT_ONLY_RE.match(stripped) and not stripped.strip("."):
        # «...» — намёк на идею, а не пустой вход.
        return False
    return bool(_NOISE_RE.match(stripped))


def is_trivial_input(text: str) -> bool:
    """Проверить, что вход слишком краток и требует уточнения.

    Одно-два слова («CRM», «приложение») не даютenough материала для
    бизнес-анализа, но это ещё не пустая идея: гейт должен уточнить, а не
    отвергнуть.

    Args:
        text: Вход пользователя.

    Returns:
        True, если вход требует уточнения.
    """
    stripped = text.strip()
    if not stripped:
        return False
    words = stripped.split()
    return len(words) <= 2 and len(stripped) <= 20


def gate_input(input_text: str) -> dict[str, Any] | None:
    """Применить гейт к входу.

    Args:
        input_text: Вход пользователя.

    Returns:
        Готовый ответ, если вход пустой; иначе None — обращаться к модели.
    """
    if is_empty_idea(input_text):
        return {
            "answer": EMPTY_IDEA_ANSWER,
            "reason": "пустая идея: ответ детерминирован, модель не вызывается",
        }
    return None
